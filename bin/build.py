#!/usr/bin/env python3
"""Assemble one self-contained HTML diagram from a spec file plus the kit's theme, styles, icons and engine.

  build.py path/to/diagram.js                  -> path/to/diagram.html
  build.py path/to/diagram.js -o docs/arch.html --theme indigo
  build.py --icons -o icons.html               -> gallery of every icon in the library
"""
import argparse
import sys
from pathlib import Path

KIT = Path(__file__).resolve().parent.parent
SRC, THEMES = KIT / "src", KIT / "themes"


def theme_css(name):
    base = (THEMES / "default.css").read_text()
    if name == "default":
        return base
    path = Path(name) if name.endswith(".css") else THEMES / f"{name}.css"
    if not path.exists():
        available = ", ".join(sorted(p.stem for p in THEMES.glob("*.css")))
        sys.exit(f"Theme not found: {path}\nAvailable: {available} (or pass a path to a .css file)")
    return base + "\n" + path.read_text()


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("spec", nargs="?", help="diagram spec (.js file defining `const DIAGRAM = {...}`)")
    ap.add_argument("-o", "--out", help="output .html (default: next to the spec)")
    ap.add_argument("--theme", default="default", help="theme name in themes/ or path to a .css file")
    ap.add_argument("--icons", action="store_true", help="build the icon gallery instead of a diagram")
    args = ap.parse_args()

    read = lambda name: (SRC / name).read_text()
    if args.icons:
        source, out = "icon library", Path(args.out or "icons.html")
        scripts = [read("icons.js"), read("gallery.js"), "mountGallery({icons:ICONS,glyphs:GLYPHS});"]
    elif args.spec:
        spec = Path(args.spec)
        if not spec.exists():
            sys.exit(f"Spec not found: {spec}")
        if "const DIAGRAM" not in spec.read_text():
            sys.exit(f"{spec} must define `const DIAGRAM = {{...}}` (see docs/spec.md)")
        source, out = spec.name, Path(args.out or spec.with_suffix(".html"))
        boot = "try{mountDiagram(DIAGRAM,{icons:ICONS,glyphs:GLYPHS})}catch(e){showDiagramError(e)}"
        scripts = [read("icons.js"), read("engine.js"), spec.read_text(), boot]
    else:
        ap.error("give a spec file, or --icons")

    html = (read("shell.html")
            .replace("{{BANNER}}", f"Generated from {source} by architecture-diagram-kit. Edit the source and rebuild; do not edit this file.")
            .replace("{{STYLE}}", theme_css(args.theme) + "\n" + read("diagram.css"))
            .replace("{{SCRIPT}}", "\n".join(scripts)))
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(html)
    print(out)


if __name__ == "__main__":
    main()
